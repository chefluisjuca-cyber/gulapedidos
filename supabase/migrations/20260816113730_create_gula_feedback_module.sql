/*
# Gula Feedback — Satisfaction Survey + Prize Roulette + Lead Capture

1. New Tables
   - `feedback_questions`: survey questions created by the admin.
     Supports single-choice (radio), multiple-choice (checkbox), and
     free-text (dissertative) types. Questions are ordered and can be
     active/inactive.
   - `feedback_prizes`: prizes for the roulette wheel. Each prize has a
     name, weight (probability), stock limit, and active flag.
   - `feedback_responses`: individual survey answers submitted by
     customers. One row per question answered, linked to a response
     session (uuid) so all answers from one survey stay grouped.
   - `feedback_leads`: customer leads captured after the survey. Stores
     name, phone, email, birthday, opt-in consent, and links to the
     restaurant.
   - `feedback_vouchers`: prize vouchers generated by the roulette.
     Each has a unique code, linked prize, linked lead, expiry date,
     and a `redeemed_at` timestamp for fraud prevention.

2. Settings
   - `restaurant_settings.feedback_voucher_validity_days` (int, default 30):
     default number of days a voucher is valid after generation.
   - `restaurant_settings.feedback_enabled` (bool, default false):
     master toggle for the feedback module.

3. Security
   - All tables have RLS enabled.
   - Customer-facing tables (questions, prizes, responses, leads,
     vouchers) allow anon + authenticated CRUD where appropriate:
     * questions/prizes: anon can SELECT active rows only (admin
       manages via authenticated).
     * responses/leads/vouchers: anon can INSERT (customer submits
       survey/lead/claims voucher); authenticated has full CRUD.
   - Voucher redemption (UPDATE redeemed_at) is restricted to
     authenticated (restaurant staff) only — anon cannot self-redeem.

4. Notes
   - All tables are multi-tenant via `restaurant_id` nullable column,
     consistent with existing project pattern.
   - Voucher codes use a 6-character alphanumeric uppercase format.
*/

-- ── feedback_questions ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS feedback_questions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id uuid REFERENCES restaurants(id) ON DELETE CASCADE,
  question_text text NOT NULL,
  question_type text NOT NULL DEFAULT 'single' CHECK (question_type IN ('single', 'multiple', 'text')),
  options text[] DEFAULT '{}',
  is_required boolean NOT NULL DEFAULT true,
  is_active boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE feedback_questions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_active_feedback_questions" ON feedback_questions;
CREATE POLICY "anon_select_active_feedback_questions" ON feedback_questions
  FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "auth_insert_feedback_questions" ON feedback_questions;
CREATE POLICY "auth_insert_feedback_questions" ON feedback_questions
  FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "auth_update_feedback_questions" ON feedback_questions;
CREATE POLICY "auth_update_feedback_questions" ON feedback_questions
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "auth_delete_feedback_questions" ON feedback_questions;
CREATE POLICY "auth_delete_feedback_questions" ON feedback_questions
  FOR DELETE TO authenticated USING (true);

