-- ── Function to generate unique voucher code ──────────────────────────
CREATE OR REPLACE FUNCTION public.generate_voucher_code()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  code text;
  attempts int := 0;
BEGIN
  LOOP
    code := '';
    FOR i IN 1..6 LOOP
      code := code || substr(chars, floor(random() * length(chars))::int + 1, 1);
    END LOOP;
    EXIT WHEN NOT EXISTS (SELECT 1 FROM feedback_vouchers WHERE code = code);
    attempts := attempts + 1;
    IF attempts > 10 THEN
      code := code || floor(random() * 1000)::text;
      EXIT;
    END IF;
  END LOOP;
  RETURN code;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.generate_voucher_code() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.generate_voucher_code() FROM anon;
